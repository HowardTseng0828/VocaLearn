const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { "zh-Hant": zhHant, en, ja };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[locale]?.[key] ?? zhHant[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function isMessageKey(key: string): key is MessageKey {
  return key in zhHant;
}

export function normalizeLocale(value: string | null | undefined): Locale | null {
  const lower = (value ?? "").toLowerCase();
  if (lower.startsWith("zh")) return "zh-Hant";
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("en")) return "en";
  return null;
}

// Locale before sign-in: the saved choice, then the browser's languages.
export function detectLocale(): Locale {
  try {
    const saved = normalizeLocale(localStorage.getItem("vl-locale"));
    if (saved) return saved;
  } catch {
    // Storage can be unavailable (private mode); fall through.
  }
  for (const language of navigator.languages ?? [navigator.language]) {
    const locale = normalizeLocale(language);
    if (locale) return locale;
  }
  return "zh-Hant";
}

// Remembers the choice locally and in a cookie the server reads at sign-up.
export function persistLocale(locale: Locale): void {
  try {
    localStorage.setItem("vl-locale", locale);
  } catch {
    // Not fatal: the account setting still applies after sign-in.
  }
  try {
    document.cookie = `vl_locale=${encodeURIComponent(locale)}; Path=/; Max-Age=31536000; SameSite=Lax`;
  } catch {
    // Sandboxed documents may refuse cookies.
  }
  document.documentElement.lang = locale;
}

const POS_KEYS: Record<string, MessageKey> = {
  adj: "pos.adj",
  a: "pos.adj",
  adv: "pos.adv",
  n: "pos.n",
  v: "pos.v",
  vt: "pos.v",
  vi: "pos.v",
  prep: "pos.prep",
  pron: "pos.pron",
  conj: "pos.conj",
  aux: "pos.aux",
  phr: "pos.phr",
  art: "pos.art",
  int: "pos.int",
  interj: "pos.int",
};

/** Turns source abbreviations such as "adj./n." into full labels in the UI language. */
export function formatPartOfSpeech(pos: string, locale: Locale): string {
  const tokens = pos.toLowerCase().split(/[\/、,，\s]+/).map((token) => token.replace(/\.$/, "")).filter(Boolean);
  const labels = tokens.map((token) => (POS_KEYS[token] ? translate(locale, POS_KEYS[token]) : token));
  return labels.filter((label, index, all) => all.indexOf(label) === index).join(" / ");
}
