// Builds data/seed-courses.sql from data/courses/<lang>.csv (ja, ko, es, de, fr).
// CSV columns: word,pos,meaning,meaning_en,level. meaning is zh-Hant (words.meaning);
// meaning_en goes to word_meanings with locale 'en'.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsv } from "./lib/word-files.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = {
  ja: "JLPT-tanos",
  ko: "NIKL-basic",
  es: "FrequencyWords-OS",
  de: "FrequencyWords-OS",
  fr: "FrequencyWords-OS",
};
const sqlEscape = (value) => String(value).replace(/'/g, "''");
const args = process.argv.slice(2);
const langIndex = args.indexOf("--lang");
const selectedLang = langIndex >= 0 ? args[langIndex + 1] : undefined;
if (langIndex >= 0 && !Object.hasOwn(SOURCES, selectedLang ?? "")) {
  throw new Error("Use --lang ja|ko|es|de|fr to build one course at a time.");
}

let sql = "-- Generated by scripts/build-course-seeds.mjs from data/courses/*.csv. See README for sources and licenses.\n" +
  "-- Requires migration 0009. Run scripts/reindex-words.sql afterwards.\n\n";
for (const [lang, source] of Object.entries(SOURCES)) {
  if (selectedLang && lang !== selectedLang) continue;
  const file = path.join(root, "data", "courses", `${lang}.csv`);
  const rows = parseCsv(fs.readFileSync(file, "utf8")).slice(1)
    .map(([word, pos, meaning, meaningEn, level]) => ({ word: word.trim(), pos, meaning, meaningEn, level: Number(level) || "NULL" }))
    .filter((row) => row.word && row.meaning);
  for (let i = 0; i < rows.length; i += 200) {
    const batch = rows.slice(i, i + 200);
    sql += "INSERT INTO words (lang, word, pos, meaning, level, source)\n" +
      `  SELECT '${lang}', v.column1, v.column2, v.column3, v.column4, '${source}' FROM (VALUES\n` +
      batch.map((row) => `    ('${sqlEscape(row.word)}', '${sqlEscape(row.pos)}', '${sqlEscape(row.meaning)}', ${row.level})`).join(",\n") +
      `\n  ) AS v LEFT JOIN words existing ON existing.lang = '${lang}' AND existing.word = v.column1\n` +
      `  WHERE existing.id IS NULL OR existing.pos IS NOT v.column2 OR existing.meaning IS NOT v.column3 OR existing.level IS NOT v.column4 OR existing.source IS NOT '${source}'\n` +
      "ON CONFLICT(lang, word) DO UPDATE SET pos=excluded.pos, meaning=excluded.meaning, level=excluded.level, source=excluded.source\n" +
      "WHERE words.pos IS NOT excluded.pos OR words.meaning IS NOT excluded.meaning OR words.level IS NOT excluded.level OR words.source IS NOT excluded.source;\n\n";
    const withEn = batch.filter((row) => row.meaningEn);
    if (!withEn.length) continue;
    sql += "INSERT INTO word_meanings (word_id, locale, meaning)\n  SELECT w.id, 'en', v.column2 FROM (VALUES\n" +
      withEn.map((row) => `    ('${sqlEscape(row.word)}', '${sqlEscape(row.meaningEn)}')`).join(",\n") +
      `\n  ) AS v JOIN words w ON w.lang = '${lang}' AND w.word = v.column1\n` +
      "  LEFT JOIN word_meanings existing ON existing.word_id = w.id AND existing.locale = 'en'\n" +
      "  WHERE existing.meaning IS NOT v.column2\n" +
      "ON CONFLICT(word_id, locale) DO UPDATE SET meaning=excluded.meaning WHERE word_meanings.meaning IS NOT excluded.meaning;\n\n";
  }
  console.log(`${lang}: ${rows.length} words`);
}
fs.writeFileSync(path.join(root, "data", selectedLang ? `seed-courses-${selectedLang}.sql` : "seed-courses.sql"), sql);
